// Writes THIRD_PARTY_LICENSES.md: every package that ends up in the app (npm runtime
// dependencies and the Rust crates compiled into the binary), with its licence text.
// Run: npm run licenses   (after changing dependencies; the release build bundles the file)
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const run = (cmd, args, cwd = root) =>
  execFileSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "ignore"] });

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;
function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), "utf8").replace(/\r\n?/g, "\n").trim() }));
}

// The Apache-2.0 terms are the same for every package: print them once at the end.
const norm = (s) => s.replace(/\s+/g, " ").trim();
const apacheMarker = norm("TERMS AND CONDITIONS FOR USE, REPRODUCTION, AND DISTRIBUTION");
const isFullApache = (t) => norm(t).includes(apacheMarker) && t.length > 9000;
let apacheText = null;

/* ---------- npm (the frontend bundle) ---------- */

const npmPaths = run("npm", ["ls", "--omit=dev", "--all", "--parseable"])
  .split("\n")
  .map((p) => p.trim())
  .filter((p) => p && p !== root);
const npm = new Map();
for (const dir of npmPaths) {
  const pkgFile = join(dir, "package.json");
  if (!existsSync(pkgFile)) continue;
  const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (npm.has(key)) continue;
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  npm.set(key, {
    name: pkg.name,
    version: pkg.version,
    license: typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? "see text"),
    url: pkg.homepage || repo || "",
    texts: licenseTexts(dir),
  });
}

/* ---------- Rust crates (the binary) ---------- */

const ownCrate = "lesepult";
const tree = run("cargo", ["tree", "-e", "normal", "--target", "all", "--prefix", "none", "-f", "{p}"], join(root, "src-tauri"))
  .split("\n")
  .map((l) => l.replace(/ \(\*\)$/, "").trim())
  .filter(Boolean);
const wanted = new Set(tree.map((l) => l.split(" ").slice(0, 2).join(" ")));
const meta = JSON.parse(run("cargo", ["metadata", "--format-version", "1"], join(root, "src-tauri")));
const crates = meta.packages
  .filter((p) => p.name !== ownCrate && wanted.has(`${p.name} v${p.version}`))
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? "see text" : "unknown"),
    url: p.repository || p.homepage || `https://crates.io/crates/${p.name}`,
    texts: licenseTexts(dirname(p.manifest_path)),
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

/* ---------- Output ---------- */

const counts = new Map();
for (const p of [...npm.values(), ...crates]) counts.set(p.license, (counts.get(p.license) ?? 0) + 1);

const section = (p) => {
  let out = `### ${p.name} ${p.version}\n\nLicense: ${p.license}${p.url ? `  \nSource: ${p.url.replace(/^git\+/, "")}` : ""}\n`;
  for (const t of p.texts) {
    if (isFullApache(t.text) && !/^notice/i.test(t.file)) {
      apacheText ??= t.text;
      out += `\n${t.file}: Apache License 2.0 (full text at the end of this file)\n`;
      continue;
    }
    out += `\n${t.file}:\n\n\`\`\`text\n${t.text.replace(/```/g, "'''")}\n\`\`\`\n`;
  }
  if (!p.texts.length) out += `\n(No licence file in the package; licensed as stated above.)\n`;
  return out;
};

let md = `# Third-party licences

Lesepult is licensed under the GNU General Public License v3.0 or later (see LICENSE). It includes
the following third-party software, each under its own licence. Generated by
\`scripts/third-party.mjs\`; do not edit by hand.

| Licence | Packages |
|---|---|
${[...counts.entries()]
  .sort((a, b) => b[1] - a[1])
  .map(([l, n]) => `| ${l} | ${n} |`)
  .join("\n")}

## Frontend (npm packages)

${[...npm.values()].sort((a, b) => a.name.localeCompare(b.name)).map(section).join("\n")}
## Application binary (Rust crates)

${crates.map(section).join("\n")}`;
if (apacheText) md += `\n## Apache License 2.0\n\n\`\`\`text\n${apacheText}\n\`\`\`\n`;
writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(
  `THIRD_PARTY_LICENSES.md: ${npm.size} npm packages, ${crates.length} crates, ${(md.length / 1024).toFixed(0)} KB`,
);
const missing = [...npm.values(), ...crates].filter((p) => !p.texts.length).map((p) => `${p.name} ${p.version} (${p.license})`);
if (missing.length) console.log(`Without a licence file (${missing.length}): ${missing.slice(0, 40).join(", ")}${missing.length > 40 ? ", …" : ""}`);
